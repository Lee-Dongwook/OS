.global keyboard_isr
.extern keyboard_handle_interrupt

keyboard_isr:
    push %rax
    push %rbx
    push %rcx
    push %rdx
    push %rsi
    push %rdi
    push %rbp
    push %r8
    push %r9
    push %r10
    push %r11
    push %r12
    push %r13
    push %r14
    push %r15

    # Windows x64 ABI의 shadow space와 호출 정렬을 보장한다.
    sub $0x28, %rsp
    call keyboard_handle_interrupt
    add $0x28, %rsp

    pop %r15
    pop %r14
    pop %r13
    pop %r12
    pop %r11
    pop %r10
    pop %r9
    pop %r8
    pop %rbp
    pop %rdi
    pop %rsi
    pop %rdx
    pop %rcx
    pop %rbx
    pop %rax
    iretq
